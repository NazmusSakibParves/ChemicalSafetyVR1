"""Builds the light rack meshes used for the side aisles from the designer model.

Input : Assets/Art/Presentable/3D/Shelf.glb   (88k triangles per rack)
Output: Assets/Art/Presentable/3D/ShelfLite_Uprights.obj (~12k tris) + ShelfLite_Beams.obj (unchanged)
Needs : pip install numpy trimesh fast-simplification. Vertices are scaled to metres (x0.337, same as the
scene builder) and the rack is centred on x/z with its base at y=0.
"""
import numpy as np
import trimesh
import fast_simplification as fs

SRC = "Assets/Art/Presentable/3D/Shelf.glb"
OUT = "Assets/Art/Presentable/3D/"
SCALE = 0.337

sc = trimesh.load(SRC)
parts = {}
for node in sc.graph.nodes_geometry:
    T, name = sc.graph[node]
    g = sc.geometry[name].copy()
    g.apply_transform(T)
    parts[name] = g

allv = np.vstack([g.vertices for g in parts.values()])
mn, mx = allv.min(0), allv.max(0)
origin = np.array([(mn[0] + mx[0]) / 2, mn[1], (mn[2] + mx[2]) / 2])
main = max(parts, key=lambda k: len(parts[k].faces))


def write(name, v, f):
    with open(OUT + name + ".obj", "w") as o:
        o.write("# generated by Tools/decimate_shelf.py\no %s\n" % name)
        for p in v:
            o.write("v %.5f %.5f %.5f\n" % tuple(p))
        for t in f:
            o.write("f %d %d %d\n" % (t[0] + 1, t[1] + 1, t[2] + 1))


for name, g in parts.items():
    v = ((g.vertices - origin) * SCALE).astype(np.float32)
    f = g.faces.astype(np.int32)
    if name == main:
        v, f = fs.simplify(v, f, target_reduction=0.93, agg=5)
        for _ in range(3):
            v, f = fs.simplify(v, f, target_reduction=0.7, agg=7)
        write("ShelfLite_Uprights", v, f)
    else:
        write("ShelfLite_Beams", v, f)
    print(name, len(g.faces), "->", len(f))
