"""Extracts the designer's chemistry props from `camical bottles1.glb` for Scenario 6, keeping every part (glass, liquid, cap, label band)
as its own mesh so the builder can give each one the right material (clear glass, liquid, plastic).

The 5 L Volatile Solvent jerrycan (`Mesh_2`) is converted to the jug frame the scene scripts use: base centre at the origin, y up,
label face toward +Z, mouth side toward -X (so tilting about Z pours toward -X). The cap is cut off the body so the container can be open.

Output: Assets/Art/Presentable/3D/Sc06/Chem/*.obj and Chem/manifest.txt (sizes, mouth position). Needs numpy, trimesh, fast-simplification.
    python Tools/prepare_sc06_chem.py
"""
import os

import numpy as np
import trimesh
import fast_simplification as fs

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(os.path.expanduser("~"), "Downloads", "Scene06 workflow-20261024T090220Z-1-001", "Scene06 workflow", "3D",
                   "camical bottles1.glb")
OUT = os.path.join(ROOT, "Assets", "Art", "Presentable", "3D", "Sc06", "Chem")
JERRY_HEIGHT = 0.30
manifest = []


def write_obj(name, v, f):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name + ".obj"), "w") as o:
        o.write("# generated by Tools/prepare_sc06_chem.py\no %s\n" % name)
        for p in v:
            o.write("v %.5f %.5f %.5f\n" % tuple(p))
        for t in f:
            o.write("f %d %d %d\n" % (t[0] + 1, t[1] + 1, t[2] + 1))


def decimate(v, f, target):
    if len(f) <= target:
        return v, f
    v2, f2 = fs.simplify(v.astype(np.float32), f.astype(np.int32), target_reduction=1.0 - target / len(f), agg=5)
    return v2, f2


def load_parts():
    sc = trimesh.load(SRC)
    parts = {}
    for node in sc.graph.nodes_geometry:
        T, name = sc.graph[node]
        g = sc.geometry[name].copy()
        g.apply_transform(T)
        parts[name] = g
    return parts


def jerrycan(parts):
    g = parts["Mesh_2"]
    v = g.vertices.copy()
    f = g.faces.copy()
    mn, mx = v.min(0), v.max(0)
    H = mx[1] - mn[1]
    xc = (mn[0] + mx[0]) * 0.5
    zc = (mn[2] + mx[2]) * 0.5
    W = mx[2] - mn[2]
    # cap: the top cluster on the high-z side
    top = v[(v[:, 1] > mx[1] - 0.01 * H) & (v[:, 2] > zc + 0.2 * W)]
    ax, az = top[:, 0].mean(), top[:, 2].mean()
    rad = np.sqrt(((top[:, [0, 2]] - [ax, az]) ** 2).sum(1)).max()
    cent = v[f].mean(1)
    dist = np.sqrt((cent[:, 0] - ax) ** 2 + (cent[:, 2] - az) ** 2)
    cap_mask = (cent[:, 1] > mx[1] - 0.15 * H) & (dist < rad * 1.08)
    s = JERRY_HEIGHT / H
    # model -> jug frame: x = (z - zc), y = y - ymin, z = -(x - xc). Unity's OBJ importer negates x, so in the scene the
    # mouth side ends up at -X (a pure rotation here, so the triangles keep their order).
    def to_local(p):
        return np.stack([(p[:, 2] - zc) * s, (p[:, 1] - mn[1]) * s, -(p[:, 0] - xc) * s], axis=1)

    def sub(mask):
        faces = f[mask]
        used = np.unique(faces)
        remap = -np.ones(len(v), int)
        remap[used] = np.arange(len(used))
        return to_local(v[used]), remap[faces]

    bv, bf = sub(~cap_mask)
    cv, cf = sub(cap_mask)
    bv, bf = decimate(bv, bf, 13000)
    cv, cf = decimate(cv, cf, 2600)
    write_obj("Sc06_Jerry", bv, bf)
    write_obj("Sc06_JerryCap", cv, cf)
    cap_bottom = (cent[cap_mask, 1].min() - mn[1]) * s
    mouth = to_local(np.array([[ax, mx[1], az]]))[0]
    cap_b = to_local(v[f[cap_mask]].reshape(-1, 3))
    manifest.append("jerry size %.3f x %.3f x %.3f (x,y,z) height %.3f" % ((bv[:, 0].max() - bv[:, 0].min()), bv[:, 1].max(),
                                                                          (bv[:, 2].max() - bv[:, 2].min()), JERRY_HEIGHT))
    manifest.append("jerry mouth x %.4f y(top) %.4f z %.4f  cap radius %.4f  cap bottom y %.4f  cap faces %d body faces %d->%d"
                    % (mouth[0], mouth[1], mouth[2], rad * s, cap_bottom, cap_mask.sum(), (~cap_mask).sum(), len(bf)))
    manifest.append("jerry bounds x %.3f..%.3f z %.3f..%.3f" % (bv[:, 0].min(), bv[:, 0].max(), bv[:, 2].min(), bv[:, 2].max()))


# group name -> (scale, [(part name, role, max triangles)]); the first part is the body that defines the base centre
GROUPS = {
    "NaOH": (0.27, [("NaOH Btl_NaOH Btl_0.001", "glass", 3200), ("NaOH Btl_NaOH Btl_0.001_1", "cap", 1200),
                    ("NaOH Btl_NaOH Btl_0.001_2", "label", 1000)]),
    "Alcohol": (0.27, [("Alcohol Btl_Alcohol Btl_0.001", "glassdark", 3200), ("Alcohol Btl_Alcohol Btl_0.001_1", "label", 1000),
                       ("Alcohol Btl_Alcohol Btl_0.001_2", "liquid", 1500)]),
    "Phenyl": (0.27, [("Ferric Chloride Cap.001_Phenylhydrazine cap_0.001_1", "glass", 3200),
                      ("Ferric Chloride Cap.001_Phenylhydrazine cap_0.001", "capblue", 1500),
                      ("Ferric Chloride Cap.001_Phenylhydrazine cap_0.001_2", "label", 1200)]),
    "Napthol": (0.30, [("Sodium NitroPrusside Cap.001_napthol Cap_0.001_1", "glassdark", 3200),
                       ("Sodium NitroPrusside Cap.001_napthol Cap_0.001", "capblack", 1500),
                       ("Sodium NitroPrusside Cap.001_napthol Cap_0.001_2", "label", 1000)]),
    "Beaker": (0.19, [("Icewater_Glass_0.001", "glass", 3500), ("Icewater_Glass_0.001_1", "liquid", 1200)]),
    "PillBottle": (0.19, [("Cube.002", "plastic", 2500), ("Cube.002_1", "label", 800), ("Cube.002_2", "capwhite", 1200)]),
    "Dropper": (0.20, [("Cylinder.001_2", "glass", 3500), ("Cylinder.001_1", "plastic", 2200), ("Cylinder.001", "capwhite", 450)]),
}


def groups(parts):
    for gname, (scale, items) in GROUPS.items():
        body = parts[items[0][0]]
        mn, mx = body.bounds
        base = np.array([(mn[0] + mx[0]) / 2, mn[1], (mn[2] + mx[2]) / 2])
        top = 0.0
        for pname, role, target in items:
            g = parts[pname]
            v = ((g.vertices - base) * scale).astype(np.float32)
            f = g.faces.astype(np.int32)
            v, f = decimate(v, f, target)
            write_obj("Sc06C_%s_%s" % (gname, role), v, f)
            top = max(top, float(v[:, 1].max()))
            manifest.append("%s %s tris %d" % (gname, role, len(f)))
        manifest.append("%s height %.3f" % (gname, top))


def main():
    parts = load_parts()
    jerrycan(parts)
    groups(parts)
    with open(os.path.join(OUT, "manifest.txt"), "w") as m:
        m.write("\n".join(manifest))
    print("\n".join(manifest))


if __name__ == "__main__":
    main()
