def read_glb(path):
    data = open(path, "rb").read()
    off = 12
    js = bin_chunk = None
    while off + 8 <= len(data):
        length, ctype = struct.unpack_from("<II", data, off)
        chunk = data[off + 8:off + 8 + length]
        if ctype == 0x4E4F534A:
            js = json.loads(chunk)
        elif ctype == 0x004E4942:
            bin_chunk = chunk
        off += 8 + length
    return js, bin_chunk


def shrink(blob, mime):
    if len(blob) < 150000:
        return blob, mime
    im = Image.open(io.BytesIO(blob))
    im.thumbnail((MAX_EDGE, MAX_EDGE), Image.Resampling.LANCZOS)
    buf = io.BytesIO()
    if im.mode in ("RGBA", "LA") and np.asarray(im.convert("RGBA"))[..., 3].min() < 250:
        im.convert("RGBA").save(buf, "PNG", optimize=True)
        return buf.getvalue(), "image/png"
    im.convert("RGB").save(buf, "JPEG", quality=JPEG_Q, optimize=True)
    return buf.getvalue(), "image/jpeg"


def write_glb(path, js, views):
    out = bytearray()
    for i, view in enumerate(views):
        while len(out) % 4:
            out.append(0)
        js["bufferViews"][i]["byteOffset"] = len(out)
        js["bufferViews"][i]["byteLength"] = len(view)
        out.extend(view)
    js["buffers"][0]["byteLength"] = len(out)
    payload = json.dumps(js, separators=(",", ":")).encode("utf-8")
    while len(payload) % 4:
        payload += b" "
    total = 12 + 8 + len(payload) + 8 + len(out)
    with open(path, "wb") as f:
        f.write(struct.pack("<4sII", b"glTF", 2, total))
        f.write(struct.pack("<I4s", len(payload), b"JSON"))
        f.write(payload)
        f.write(struct.pack("<I4s", len(out), b"BIN\x00"))
        f.write(out)


def one(src_name, dst_name):
    src = os.path.join(SRC, "3D", src_name)
    js, blob = read_glb(src)
    views = []
    for bv in js["bufferViews"]:
        start = bv.get("byteOffset", 0)
        views.append(bytearray(blob[start:start + bv["byteLength"]]))
    for im in js.get("images", []):
        vi = im.get("bufferView")
        if vi is None:
            continue
        new, mime = shrink(bytes(views[vi]), im.get("mimeType", ""))
        views[vi] = bytearray(new)
        im["mimeType"] = mime
    dst = os.path.join(OUT3D, dst_name)
    write_glb(dst, js, views)
    print(src_name, os.path.getsize(src) // 1024, "KB ->", dst_name, os.path.getsize(dst) // 1024, "KB")


def write_obj(path, v, f):
    with open(path, "w") as o:
        o.write("# generated by Tools/prepare_sc06_models.py\no %s\n" % os.path.basename(path)[:-4])
        for p in v:
            o.write("v %.5f %.5f %.5f\n" % tuple(p))
        for t in f:
            o.write("f %d %d %d\n" % (t[0] + 1, t[1] + 1, t[2] + 1))


def bottle_parts():
    sc = trimesh.load(os.path.join(SRC, "3D", "camical bottles1.glb"))
    # each bottle and its cap share one origin so the cap still sits on the neck: centre both on the body
    centres = {}
    geoms = {}
    for node in sc.graph.nodes_geometry:
        T, name = sc.graph[node]
        if name in PARTS:
            g = sc.geometry[name].copy()
            g.apply_transform(T)
            geoms[name] = g
    groups = [("NaOH Btl_NaOH Btl_0.001", ["NaOH Btl_NaOH Btl_0.001_1"]),
              ("Alcohol Btl_Alcohol Btl_0.001", ["Alcohol Btl_Alcohol Btl_0.001_1"]),
              ("Ferric Chloride Cap.001_Phenylhydrazine cap_0.001_1",
               ["Ferric Chloride Cap.001_Phenylhydrazine cap_0.001"])]
    for body, others in groups:
        b = geoms[body].bounds
        centres[body] = np.array([(b[0][0] + b[1][0]) / 2, b[0][1], (b[0][2] + b[1][2]) / 2])
        for o in others:
            centres[o] = centres[body]
    for name, (out, target) in PARTS.items():
        g = geoms[name]
        c = centres.get(name)
        if c is None:
            b = g.bounds
            c = np.array([(b[0][0] + b[1][0]) / 2, b[0][1], (b[0][2] + b[1][2]) / 2])
        v = (g.vertices - c).astype(np.float32)
        f = g.faces.astype(np.int32)
        if len(f) > target:
            v, f = fs.simplify(v, f, target_reduction=1.0 - target / len(f), agg=6)
        write_obj(os.path.join(OUT3D, out + ".obj"), v, f)
        print(out, len(g.faces), "->", len(f), "ext", (v.max(0) - v.min(0)).round(3).tolist())


