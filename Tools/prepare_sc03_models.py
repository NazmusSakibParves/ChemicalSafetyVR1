"""Prepares the designer Scenario 3 models for the Quest APK.

Source: Downloads/Scene03 workflow-.../Scene03 workflow/3D and 2D/Resources.
Output (Assets/Art/Presentable):
  3D/Sc03Drum.glb       hero Organic Peroxide drum (crystals + label), textures capped at 1024
  3D/Sc03OldDrums.glb   old drum pair, textures capped at 1024
  3D/Sc03Shelf.obj      one 3-tier bay of "old shelve 01.glb", decimated (the original is 90k triangles), metres,
                        centred on x/z with its base at y=0
  2D/Sc03/SDS_SC03.png  new SDS clipboard sheet

    python Tools/prepare_sc03_models.py
Needs: pip install numpy pillow trimesh fast-simplification
"""
import io
import json
import os
import shutil
import struct

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(os.path.expanduser("~"), "Downloads", "Scene03 workflow-20261020T164953Z-1-001", "Scene03 workflow")
ART = os.path.join(ROOT, "Assets", "Art", "Presentable")
MAX_EDGE = 1024
SHELF_SCALE = 0.3  # raw bay is 8.66 x 11.73 x 2.33; this gives about 2.6 x 3.5 x 0.7 m
SHELF_TRIS = 14000


def read_glb(path):
    data = open(path, "rb").read()
    off = 12
    js = blob = None
    while off + 8 <= len(data):
        length, ctype = struct.unpack_from("<II", data, off)
        chunk = data[off + 8:off + 8 + length]
        if ctype == 0x4E4F534A:
            js = json.loads(chunk)
        elif ctype == 0x004E4942:
            blob = chunk
        off += 8 + length
    return js, blob


def shrink(blob):
    im = Image.open(io.BytesIO(blob))
    if max(im.size) <= MAX_EDGE and len(blob) < 400000:
        return blob, None
    has_alpha = im.mode == "RGBA" and im.split()[3].getextrema()[0] < 250
    im.thumbnail((MAX_EDGE, MAX_EDGE), Image.Resampling.LANCZOS)
    buf = io.BytesIO()
    if has_alpha:
        im.save(buf, "PNG", optimize=True)
        return buf.getvalue(), "image/png"
    im.convert("RGB").save(buf, "JPEG", quality=78, optimize=True)
    return buf.getvalue(), "image/jpeg"


def shrink_glb(src, dst):
    js, blob = read_glb(src)
    views = [bytearray(blob[bv.get("byteOffset", 0):bv.get("byteOffset", 0) + bv["byteLength"]])
             for bv in js["bufferViews"]]
    for im in js.get("images", []):
        vi = im.get("bufferView")
        if vi is None:
            continue
        new, mime = shrink(bytes(views[vi]))
        views[vi] = bytearray(new)
        if mime:
            im["mimeType"] = mime
    out = bytearray()
    for i, view in enumerate(views):
        while len(out) % 4:
            out.append(0)
        js["bufferViews"][i]["byteOffset"] = len(out)
        js["bufferViews"][i]["byteLength"] = len(view)
        out.extend(view)
    js["buffers"][0]["byteLength"] = len(out)
    payload = json.dumps(js, separators=(",", ":")).encode("utf-8")
    while len(payload) % 4:
        payload += b" "
    total = 12 + 8 + len(payload) + 8 + len(out)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "wb") as f:
        f.write(struct.pack("<4sII", b"glTF", 2, total))
        f.write(struct.pack("<I4s", len(payload), b"JSON"))
        f.write(payload)
        f.write(struct.pack("<I4s", len(out), b"BIN\x00"))
        f.write(out)
    print("wrote", dst, os.path.getsize(dst))


def decimate_shelf(src, dst):
    import fast_simplification as fs
    import trimesh

    sc = trimesh.load(src)
    verts, faces, base = [], [], 0
    for node in sc.graph.nodes_geometry:
        T, name = sc.graph[node]
        g = sc.geometry[name].copy()
        g.apply_transform(T)
        verts.append(g.vertices)
        faces.append(g.faces + base)
        base += len(g.vertices)
    v = np.vstack(verts)
    f = np.vstack(faces).astype(np.int32)
    mn, mx = v.min(0), v.max(0)
    origin = np.array([(mn[0] + mx[0]) / 2, mn[1], (mn[2] + mx[2]) / 2])
    v = ((v - origin) * SHELF_SCALE).astype(np.float32)
    target = max(0.05, 1.0 - SHELF_TRIS / len(f))
    v2, f2 = fs.simplify(v, f, target_reduction=target, agg=5)
    # decimation leaves long hair-thin slivers (the "strings" between posts): drop them
    a, b, c = v2[f2[:, 0]], v2[f2[:, 1]], v2[f2[:, 2]]
    area = np.linalg.norm(np.cross(b - a, c - a), axis=1) / 2
    longest = np.maximum.reduce([np.linalg.norm(b - a, axis=1), np.linalg.norm(c - b, axis=1),
                                 np.linalg.norm(a - c, axis=1)])
    f2 = f2[~((longest > 0.25) & (area / np.maximum(longest, 1e-6) < 0.004))]
    with open(dst, "w") as o:
        o.write("# generated by Tools/prepare_sc03_models.py\no Sc03Shelf\n")
        for p in v2:
            o.write("v %.5f %.5f %.5f\n" % tuple(p))
        for t in f2:
            o.write("f %d %d %d\n" % (t[0] + 1, t[1] + 1, t[2] + 1))
    print("wrote", dst, len(f), "->", len(f2), "tris, size", (v2.max(0) - v2.min(0)).round(2))


def main():
    shrink_glb(os.path.join(SRC, "3D", "chemical dram.glb"), os.path.join(ART, "3D", "Sc03Drum.glb"))
    shrink_glb(os.path.join(SRC, "3D", "Old drams.glb"), os.path.join(ART, "3D", "Sc03OldDrums.glb"))
    decimate_shelf(os.path.join(SRC, "3D", "old shelve 01.glb"), os.path.join(ART, "3D", "Sc03Shelf.obj"))
    out2d = os.path.join(ART, "2D", "Sc03")
    os.makedirs(out2d, exist_ok=True)
    shutil.copyfile(os.path.join(SRC, "2D", "Resources", "SDS sheet.png"), os.path.join(out2d, "SDS_SC03.png"))
    shutil.copyfile(os.path.join(SRC, "2D", "Resources", "drum_label_transparent (1).png"),
                    os.path.join(out2d, "DrumLabel_SC03.png"))
    print("done")


if __name__ == "__main__":
    main()
